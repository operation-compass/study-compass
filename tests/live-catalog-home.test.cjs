'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('home-v2.html','utf8');
const model=html.split('// BEGIN CATALOG MODEL')[1].split('// END CATALOG MODEL')[0];
const ctx=vm.createContext({});vm.runInContext('const subjects=["国語","数学","英語","理科","社会"];'+model,ctx);
const question=(id,subject,major,minor)=>({id,subject,major,minor});
ctx.payload={schema:1,questions:[question('q1','社会','歴史','古代'),question('q2','社会','歴史','新単元'),question('q3','英語','文法','過去形'),question('q4','社会','歴史','新単元')]};
vm.runInContext('var catalog=buildCatalog(payload)',ctx);
assert.equal(vm.runInContext('totalFor(catalog.units,"社会")',ctx),3);
assert.equal(vm.runInContext('totalFor(catalog.units,"社会","歴史","新単元")',ctx),2);
assert.equal(vm.runInContext('totalFor(catalog.units,"数学")',ctx),0);
assert.equal(vm.runInContext('currentQuestion("q1",{subject:"社会",major:"歴史",minor:"古代"},catalog.byQuestion)',ctx),true);
assert.equal(vm.runInContext('currentQuestion("withdrawn",{subject:"社会",major:"歴史",minor:"古代"},catalog.byQuestion)',ctx),false);
assert.equal(vm.runInContext('currentQuestion("q1",{subject:"社会",major:"歴史",minor:"新単元"},catalog.byQuestion)',ctx),false);
assert.throws(()=>vm.runInContext('buildCatalog({schema:1,questions:[payload.questions[0],payload.questions[0]]})',ctx));
assert.throws(()=>vm.runInContext('buildCatalog({schema:2,questions:[]})',ctx));
assert.equal(vm.runInContext('totalFor(buildCatalog({schema:1,questions:[]}).units,"社会")',ctx),0);
assert(html.includes('const KEY="shirunoera.learning.v1"'));
assert(html.includes('fetch("/api/question-catalog.json"'));
assert(!html.includes("2026年11月23日時点"));
for(const script of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g))new vm.Script(script[1]);
console.log('PASS live catalog counts, new units, current ID matching, empty/error/duplicate cases and script syntax');
